//===-- LVXInstPrinter.h - Convert LVX MCInst to asm syntax -----*- C++ -*-===//
//
// This class prints an LVX MCInst to a .s file. Modeled on
// LanaiInstPrinter.h (confirmed current in this checkout).
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_LVX_MCTARGETDESC_LVXINSTPRINTER_H
#define LLVM_LIB_TARGET_LVX_MCTARGETDESC_LVXINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class LVXInstPrinter : public MCInstPrinter {
public:
  LVXInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  // Overload for OPERAND_PCREL operands (brtarget11s2/17s2/27s2): LVX
  // direct branch/call targets are always lowered to a plain symbol
  // expression by LVXMCInstLower (no separate hi/lo split to compute from
  // Address), so this just forwards to the 3-arg form -- kept as its own
  // overload only because the tblgen-generated printInstruction below
  // calls this exact signature for those operand classes.
  void printOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                    raw_ostream &O);
  void printRegName(raw_ostream &OS, MCRegister Reg) override;

  // Modifier-operand printers (LVXInstrFormats.td's PrintMethod fields),
  // backed by the suffix tables in LVXModifiers.h (auto-generated from
  // lvx_Modifier.yml). Called by the tblgen-generated printInstruction
  // below for any instruction using one of these operand types.
  void printCcbcomp(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBcucond(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printIntcomp(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printFloatcomp(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printFloatmode(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printSignextw(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printHighmult(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printWidemult(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMostsig(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printFnegate(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printVariant(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCachelev(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printAccesses(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printConjugate(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImultiply(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Autogenerated by tblgen (LVXGenAsmWriter.inc).
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  static const char *getRegisterName(MCRegister Reg);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_LVX_MCTARGETDESC_LVXINSTPRINTER_H
