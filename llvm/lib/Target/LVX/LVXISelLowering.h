//===-- LVXISelLowering.h - LVX DAG Lowering Interface ----------*- C++ -*-===//
//
// This file defines the interfaces that LVX uses to lower LLVM code into a
// selection DAG. Modeled on LanaiISelLowering.h (confirmed current in this
// checkout), trimmed to what's needed for Phase 3: type/calling-convention
// setup plus LowerReturn/LowerCall/LowerFormalArguments. Lanai's many
// LowerXXX(SDValue, SelectionDAG&) custom-lowering hooks (LowerGlobalAddress,
// LowerSELECT_CC, LowerSHL_PARTS, etc.) are deferred — LVX doesn't yet need
// any of them since LowerOperation has nothing routed to it until specific
// IR patterns are found to need custom lowering.
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_LVX_LVXISELLOWERING_H
#define LLVM_LIB_TARGET_LVX_LVXISELLOWERING_H

#include "LVXRegisterInfo.h"
#include "llvm/CodeGen/SelectionDAG.h"
#include "llvm/CodeGen/TargetLowering.h"

namespace llvm {

class LVXSubtarget;

// LVXISD::{CALL, RET_GLUE, ...} are generated by TableGen into
// LVXGenSDNodeInfo.inc (via -gen-sd-node-info), included through
// LVXSelectionDAGInfo.h -> LVXSubtarget.h. No hand-written enum needed.

class LVXTargetLowering : public TargetLowering {
public:
  LVXTargetLowering(const TargetMachine &TM, const LVXSubtarget &STI);

  // LowerOperation - Provide custom lowering hooks for some operations.
  // Routed here so far: the i128 shifts (lowerShift128) and the i128
  // multiply (lowerMul128).
  SDValue LowerOperation(SDValue Op, SelectionDAG &DAG) const override;

  // LVX has real fused multiply-add hardware (FFMAD/FFMAW), so llvm.fmuladd
  // should become a single ISD::FMA rather than a separate multiply and add.
  // The base class answers false, which is why "a*b + c" was still coming out
  // as fmuld+faddd even with FMA declared Legal and patterns in place: the
  // fmuladd intrinsic is only turned into an FMA node when the target says
  // fusing is profitable.
  EVT getSetCCResultType(const DataLayout &DL, LLVMContext &Ctx,
                         EVT VT) const override;

  bool isFMAFasterThanFMulAndFAdd(const MachineFunction &MF,
                                  EVT VT) const override;

  bool CanLowerReturn(CallingConv::ID CallConv, MachineFunction &MF,
                      bool IsVarArg,
                      const SmallVectorImpl<ISD::OutputArg> &Outs,
                      LLVMContext &Context, const Type *RetTy) const override;

  Register getRegisterByName(const char *RegName, LLT VT,
                             const MachineFunction &MF) const override;

  std::pair<unsigned, const TargetRegisterClass *>
  getRegForInlineAsmConstraint(const TargetRegisterInfo *TRI,
                               StringRef Constraint, MVT VT) const override;

  ConstraintWeight
  getSingleConstraintMatchWeight(AsmOperandInfo &Info,
                                 const char *Constraint) const override;

private:
  SDValue lowerShift128(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerMul128(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerVectorExtend(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerVASTART(SDValue Op, SelectionDAG &DAG) const;

public:
  // A vector of 64 bits or less has no legal type here -- the legal vector
  // types start at 128 bits -- so for argument and return purposes it travels
  // as the one i64 GPR it fits in, which the generic code then bitcasts into
  // place. Without saying so, a `float __attribute__((vector_size(8)))`
  // parameter made SelectionDAGBuilder assemble the value from parts whose
  // size did not match the register it had been assigned ("Part type sizes
  // don't match!"). GCC answers the same question with
  // lvx_vector_mode_supported_p, which claims V8QI/V4HI/V2SI/V2SF/V4HF and
  // widens their ARITHMETIC onto the 128-bit unit; passing them in a GPR is
  // the matching choice.
  MVT getRegisterTypeForCallingConv(LLVMContext &Context, CallingConv::ID CC,
                                    EVT VT) const override;
  unsigned getNumRegistersForCallingConv(LLVMContext &Context,
                                         CallingConv::ID CC,
                                         EVT VT) const override;

private:
  SDValue lowerCopySign(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerBuildVectorPacked(SDValue Op, SelectionDAG &DAG) const;
  SDValue lowerExtractLane(SDValue Op, SelectionDAG &DAG) const;

  SDValue LowerCall(TargetLowering::CallLoweringInfo &CLI,
                    SmallVectorImpl<SDValue> &InVals) const override;

  SDValue LowerFormalArguments(SDValue Chain, CallingConv::ID CallConv,
                               bool IsVarArg,
                               const SmallVectorImpl<ISD::InputArg> &Ins,
                               const SDLoc &DL, SelectionDAG &DAG,
                               SmallVectorImpl<SDValue> &InVals) const override;

  SDValue LowerReturn(SDValue Chain, CallingConv::ID CallConv, bool IsVarArg,
                      const SmallVectorImpl<ISD::OutputArg> &Outs,
                      const SmallVectorImpl<SDValue> &OutVals,
                      const SDLoc &DL, SelectionDAG &DAG) const override;

  const LVXRegisterInfo *TRI;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_LVX_LVXISELLOWERING_H
