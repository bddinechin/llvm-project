//===-- LVXSubtarget.h - Define Subtarget for the LVX ----------*- C++ -*-===//
//
// This file declares the LVX specific subclass of TargetSubtargetInfo.
// Modeled on LanaiSubtarget.h (confirmed current in this checkout).
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_LVX_LVXSUBTARGET_H
#define LLVM_LIB_TARGET_LVX_LVXSUBTARGET_H

#include "LVXFrameLowering.h"
#include "LVXISelLowering.h"
#include "LVXInstrInfo.h"
#include "LVXSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

// GET_SUBTARGETINFO_ENUM must be defined alongside GET_SUBTARGETINFO_HEADER
// for the same reason documented in LVXRegisterInfo.h / LVXInstrInfo.h:
// LVXGenSubtargetInfo.inc treats these as independent guarded sections.
// LVX has no real SubtargetFeature defs yet (just the "generic"
// ProcessorModel placeholder), so this enum is currently empty/trivial,
// but defining it keeps the pattern consistent and avoids the same class
// of "not a member of llvm::LVX" error if a TARGET_DESC section
// elsewhere ever needs it.
#define GET_SUBTARGETINFO_ENUM
#define GET_SUBTARGETINFO_HEADER
#include "LVXGenSubtargetInfo.inc"

namespace llvm {

class LVXSubtarget : public LVXGenSubtargetInfo {
public:
  // This constructor initializes the data members to match that of the
  // specified triple.
  LVXSubtarget(const Triple &TargetTriple, StringRef Cpu,
              StringRef FeatureString, const TargetMachine &TM,
              const TargetOptions &Options, CodeModel::Model CodeModel,
              CodeGenOptLevel OptLevel);

  // Parses features string setting specified subtarget options. Definition
  // of function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
  LVXSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);
  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  const LVXInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const LVXRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const LVXTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const LVXSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  LVXInstrInfo InstrInfo;
  LVXFrameLowering FrameLowering;
  LVXTargetLowering TLInfo;
  LVXSelectionDAGInfo TSInfo;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_LVX_LVXSUBTARGET_H
