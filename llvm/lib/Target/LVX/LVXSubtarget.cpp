using namespace llvm;

// The CPU name to use when none was given. It has to be a processor this
// target knows: an unrecognized one draws a warning, and -- since the
// itinerary is looked up by CPU name -- leaves the subtarget with no
// scheduling model at all, which silently turns LVXBundler off. That is how
// `llc` with no -mcpu came to emit one instruction per bundle.
static StringRef normalizeCPU(StringRef CPU) {
  return CPU.empty() ? StringRef("generic") : CPU;
}

void LVXSubtarget::initSubtargetFeatures(StringRef CPU, StringRef FS) {
  StringRef CPUName = normalizeCPU(CPU);
  // ParseSubtargetFeatures is generated by tblgen from the
  // SubtargetFeature/ProcessorModel defs in LVXInstrInfo.td (currently
  // just the "generic" placeholder added for Phase 3 — there are no real
  // SubtargetFeature defs yet, so this has nothing to parse beyond CPU
  // name validation).
  ParseSubtargetFeatures(CPUName, /*TuneCPU=*/CPUName, FS);
}

LVXSubtarget &LVXSubtarget::initializeSubtargetDependencies(StringRef CPU,
                                                            StringRef FS) {
  initSubtargetFeatures(CPU, FS);
  return *this;
}

LVXSubtarget::LVXSubtarget(const Triple &TargetTriple, StringRef Cpu,
                          StringRef FeatureString, const TargetMachine &TM,
                          const TargetOptions & /*Options*/,
                          CodeModel::Model /*CodeModel*/,
                          CodeGenOptLevel /*OptLevel*/)
    : LVXGenSubtargetInfo(TargetTriple, normalizeCPU(Cpu),
                          /*TuneCPU=*/normalizeCPU(Cpu), FeatureString),
      InstrInfo(initializeSubtargetDependencies(Cpu, FeatureString)),
      InstrItins(getInstrItineraryForCPU(normalizeCPU(Cpu))),
      FrameLowering(*this), TLInfo(TM, *this), TSInfo() {}
