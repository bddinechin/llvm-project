//===-- LVXISelDAGToDAG.h - LVX DAG-to-DAG Instruction Selector -*- C++ -*-===//
//
// This file defines the LVX-specific DAG-to-DAG instruction selector.
// Phase 3 stub: the class exists and links, but Select() does not yet
// implement any of the custom selection logic deferred from
// LVXInstrInfo.td (CALL/ICALL direct-vs-indirect dispatch, the
// LWZ/LWS/LD/_idx variant-modifier selection, CLSD). Those are filled in
// once LVXISelLowering's basic call/return lowering is verified working.
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_LVX_LVXISELDAGTODAG_H
#define LLVM_LIB_TARGET_LVX_LVXISELDAGTODAG_H

#include "LVXTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"

namespace llvm {

FunctionPass *createLVXISelDag(LVXTargetMachine &TM,
                               CodeGenOptLevel OptLevel);

class LVXDAGToDAGISel : public SelectionDAGISel {
public:
  static char ID;

  LVXDAGToDAGISel() = delete;

  LVXDAGToDAGISel(LVXTargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  void Select(SDNode *N) override;

// SelectCode and CheckNodePredicate are generated by LVXGenDAGISel.inc.
// GET_DAGISEL_BODY in the .cpp emits their *definitions*; this
// GET_DAGISEL_DECL block (the matching half of that same generated file)
// supplies the *declarations* the .cpp's out-of-line definitions need to
// match against -- confirmed directly from LVXGenDAGISel.inc's own
// header comment, which documents this two-macro DECL/BODY split.
// Omitting this half was the original bug: the .cpp's definitions had
// nothing to match.
#define GET_DAGISEL_DECL
#include "LVXGenDAGISel.inc"
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_LVX_LVXISELDAGTODAG_H
